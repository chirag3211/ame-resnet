#!/usr/bin/env python3
"""Emit weights_inc.c: embeds the riscv-dnn bindata files with .incbin and exposes them as tables.
   usage: gen_weights_inc.py <bindata_dir> > weights_inc.c
Needed files: conv2d[_N]_kernel.bin (53, fp16 HWIO), batch_normalization[_N]_new_alpha/new_beta.bin (49 each, fp16),
dense_kernel.bin (fp16 [2048][1001]), dense_bias.bin (fp32 [1001]), imagenet_pic_data.bin (fp16 NHWC, 69 images)."""
import os, sys
d = os.path.abspath(sys.argv[1])
def name(base, i, suffix): return f"{base}{'' if i == 0 else '_' + str(i)}{suffix}"
files = []
conv  = [name("conv2d", i, "_kernel") for i in range(53)]
alpha = [name("batch_normalization", i, "_new_alpha") for i in range(49)]
beta  = [name("batch_normalization", i, "_new_beta") for i in range(49)]
misc  = ["dense_kernel", "dense_bias", "imagenet_pic_data"]
for n in conv + alpha + beta + misc:
    p = f"{d}/{n}.bin"
    if not os.path.isfile(p): sys.exit(f"missing {p}")
    files.append((n, p, os.path.getsize(p)))
exp = {"dense_kernel": 2048 * 1001 * 2, "dense_bias": 1001 * 4, "imagenet_pic_data": 69 * 224 * 224 * 3 * 2}
for n, p, sz in files:
    if n in exp and sz != exp[n]: sys.exit(f"{p}: size {sz}, expected {exp[n]}")
out = ["/* generated by gen_weights_inc.py: do not edit */", "#include <stdint.h>", "#include \"weights_inc.h\""]
for n, p, sz in files:
    out.append(f'__asm__(".pushsection .rodata\\n.balign 64\\n.global w_{n}\\nw_{n}:\\n.incbin \\"{p}\\"\\n.popsection");')
    out.append(f"extern const uint8_t w_{n}[];")
def table(tname, names): return f"const uint16_t *const {tname}[{len(names)}] = {{\n" + ",\n".join(f"  (const uint16_t *)w_{n}" for n in names) + "\n};"
out += [table("g_conv_w", conv), table("g_bn_alpha", alpha), table("g_bn_beta", beta),
        "const uint16_t *const g_dense_w = (const uint16_t *)w_dense_kernel;",
        "const float *const g_dense_b = (const float *)w_dense_bias;",
        "const uint16_t *const g_pics = (const uint16_t *)w_imagenet_pic_data;"]
print("\n".join(out))
